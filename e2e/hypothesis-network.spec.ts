import { expect, test } from "@playwright/test";

test("сеть гипотез управляется и сохраняет все направления связей", async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/hypotheses");
  const map = page.locator(".hyp-map");
  await expect(map.locator("canvas").first()).toBeAttached();
  for (const name of ["Приблизить карту", "Отдалить карту", "Показать всю карту"]) await map.getByRole("button", { name }).click();
  const mention = map.getByRole("checkbox", { name: "УПОМИНАНИЕ" });
  await mention.uncheck();
  await expect(mention).not.toBeChecked();
  const beforeSelection = await map.locator(".hyp-map-canvas").screenshot();
  const list = page.getByRole("list", { name: "Гипотезы на карте" });
  await page.getByLabel("ПОИСК ПО ID ИЛИ НАЗВАНИЮ").fill("H-003");
  await list.getByRole("button", { name: /H-003/ }).click();
  const detail = page.locator(".hyp-graph-detail");
  await expect.poll(async () => (await map.locator(".hyp-map-canvas").screenshot()).equals(beforeSelection)).toBe(false);
  const h001 = detail.getByRole("listitem").filter({ has: page.getByRole("link", { name: "H-001 ↗" }) });
  await expect(h001).toHaveCount(1);
  await expect(h001).toContainText("упоминает выбранную");
  await expect(h001).toContainText("упомянута в выбранной");
  await page.addStyleTag({ content: ".topbar, nextjs-portal { visibility: hidden !important; }" });
  await detail.screenshot({ path: test.info().outputPath("selection.png"), animations: "disabled" });
  await h001.getByRole("button", { name: "Выбрать H-001 на карте" }).click();
  await expect(detail.locator(".section-kicker")).toContainText("H-001");
  await expect(detail.locator("h3")).toBeFocused();
  await expect(page.getByLabel("ПОИСК ПО ID ИЛИ НАЗВАНИЮ")).toHaveValue("");
  await detail.getByRole("button", { name: "← НАЗАД: H-003" }).click();
  await expect(detail.locator(".section-kicker")).toContainText("H-003");
  await expect(detail.locator("h3")).toBeFocused();
  await detail.getByRole("button", { name: "ПОКАЗАТЬ НА КАРТЕ ⌖" }).click();
  await mention.check();
  await detail.getByRole("button", { name: "СБРОСИТЬ ВЫБОР" }).click();
  await expect(detail).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await map.getByRole("button", { name: "Показать всю карту" }).click();
  await page.addStyleTag({ content: ".topbar, nextjs-portal { visibility: hidden !important; }" });
  await map.screenshot({ path: test.info().outputPath("network.png"), animations: "disabled" });
  expect(errors).toEqual([]);
});

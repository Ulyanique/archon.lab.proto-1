import { expect, test } from "@playwright/test";

test("история и сцена сохраняют контекст, знания и ссылку на исходный текст", async ({ page }, info) => {
  test.setTimeout(90_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error" && /hydrat/i.test(message.text())) errors.push(message.text()); });
  await page.goto("/studio");
  await page.getByRole("link", { name: "ОТКРЫТЬ КАРТОЧКУ ИСТОРИИ ↗" }).click();
  await expect(page.getByRole("heading", { name: "Scrypt — закрытое поручение" })).toBeVisible();
  await expect(page.getByText("РАБОЧИЙ ВАРИАНТ / НЕ КАНОН")).toBeVisible();
  await expect(page.getByText(/редакторский, а не хронология/)).toBeVisible();
  const scene = page.locator("#scene-scrypt-request-001");
  await expect(scene.getByRole("heading", { name: "Запрос к хранителю" })).toBeVisible();
  await expect(scene).toContainText("Не знает, есть ли в записи нужный документ");
  await expect(scene).toContainText("Место и время не определены");
  const variant = page.locator("#scene-scrypt-home-variant-002");
  await expect(variant).toContainText("условное продолжение");
  await expect(variant).toContainText("Не знает содержания записи");
  await expect(variant.getByRole("link", { name: /H-029/ })).toHaveAttribute("href", "/hypotheses/H-029");
  await expect(page.getByRole("complementary", { name: "Контекст истории" }).getByRole("link", { name: /H-028/ })).toHaveAttribute("href", "/hypotheses/H-028");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => document.fonts.ready);
  await page.addStyleTag({ content: ".topbar, nextjs-portal { visibility: hidden !important; }" });
  await page.screenshot({ path: info.outputPath("story.png"), fullPage: true, animations: "disabled" });
  await scene.getByRole("link", { name: "ЧИТАТЬ ПРОБУ В ИСТОЧНИКЕ ↗" }).click();
  await expect(page.getByRole("heading", { name: "Проба сцены / проза" })).toBeVisible();
  await expect(page.locator(".prose")).toContainText("Хранитель не открыл запись");
  await page.goto("/stories/story-scrypt-request#scene-scrypt-home-variant-002");
  await page.locator("#scene-scrypt-home-variant-002").getByRole("link", { name: "ЧИТАТЬ ПРОБУ В ИСТОЧНИКЕ ↗" }).click();
  await expect(page.getByRole("heading", { name: "Проба сцены / вариант с домом" })).toBeVisible();
  await expect(page.locator(".prose")).toContainText("Мне нужно доказать, что мне разрешили там жить");
  await page.goto("/stories");
  await expect(page.getByRole("link", { name: /Scrypt — закрытое поручение/ })).toBeVisible();
  await page.goto("/search");
  await page.getByLabel("ИСТОЧНИК").selectOption("draft");
  await page.getByRole("searchbox", { name: "ПОИСК ПО АРХИВУ" }).fill("scene-scrypt-request-001");
  await expect(page.locator(".search-result")).toHaveCount(1);
  await expect(page.locator(".search-result")).toHaveAttribute("href", "/stories/story-scrypt-request");
  expect(errors).toEqual([]);
});

import { expect, test } from "@playwright/test";

test("вторая история связана с гипотезами и условной пробой", async ({ page }, info) => {
  test.setTimeout(90_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error" && /hydrat/i.test(message.text())) errors.push(message.text()); });
  await page.goto("/stories");
  await expect(page.getByRole("link", { name: /Scrypt — закрытое поручение/ })).toBeVisible();
  await page.getByRole("link", { name: /Окно отгрузки/ }).click();
  await expect(page.getByRole("heading", { name: "Окно отгрузки", exact: true })).toBeVisible();
  await expect(page.getByText("РАБОЧИЙ ВАРИАНТ / НЕ КАНОН")).toBeVisible();
  const scene = page.locator("#scene-dispatch-reservation-001");
  await expect(scene).toContainText("физическая причина ограничения отправки требует исследования");
  await expect(scene).toContainText("Не знает подтверждённой срочности ремонта");
  await expect(scene).toContainText("Ответственный за приоритет");
  await expect(scene.getByRole("link", { name: /H-031/ })).toHaveAttribute("href", "/hypotheses/H-031");
  const review = page.locator("#story-review");
  await expect(review).toContainText("0 / СИГНАЛОВ");
  await expect(review).toContainText("не означает, что история завершена или непротиворечива");
  await expect(review).toContainText("H-022");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => document.fonts.ready);
  await page.addStyleTag({ content: ".topbar, nextjs-portal { visibility: hidden !important; }" });
  await page.screenshot({ path: info.outputPath("dispatch-story.png"), fullPage: true, animations: "disabled" });
  await scene.getByRole("link", { name: "ЧИТАТЬ ПРОБУ В ИСТОЧНИКЕ ↗" }).click();
  await expect(page.getByRole("heading", { name: "Проба сцены / спор о резерве" })).toBeVisible();
  await expect(page.locator(".prose")).toContainText("Ни одна из сторон ещё не предоставила всего");
  await page.goto("/hypotheses/H-031");
  await expect(page.locator(".workshop-aside").getByRole("link", { name: "H-022 ↗" })).toBeVisible();
  await expect(page.locator(".workshop-aside section").filter({ hasText: "ИСТОРИИ / НЕ КАНОН" }).getByRole("link", { name: /Окно отгрузки/ })).toHaveAttribute("href", "/stories/story-dispatch-window");
  await page.goto("/hypotheses/H-032");
  await expect(page.locator(".workshop-aside").getByRole("link", { name: "H-022 ↗" })).toBeVisible();
  await page.locator(".workshop-aside").getByRole("link", { name: /Отгрузка — физика и решения/ }).click();
  await expect(page.getByRole("heading", { name: "Отгрузка — физика и решения" })).toBeVisible();
  await expect(page.locator(".prose")).toContainText("не срок доставки груза");
  await expect(page.locator(".prose").getByRole("link", { name: /JPL: Near-Earth/ })).toHaveAttribute("href", /echo\.jpl\.nasa\.gov/);
  await expect(page.locator(".prose").getByRole("link", { name: /Love и Reagan/ })).toHaveAttribute("href", "https://doi.org/10.1016/j.actaastro.2013.05.003");
  await page.goto("/studio/continuity");
  await expect(page.locator(".continuity-card").filter({ has: page.getByRole("heading", { name: "Окно отгрузки" }) })).toContainText("0 сигналов");
  await page.goto("/search");
  await page.getByLabel("ИСТОЧНИК").selectOption("draft");
  await page.getByRole("searchbox", { name: "ПОИСК ПО АРХИВУ" }).fill("scene-dispatch-reservation-001");
  await expect(page.locator('.search-result[href="/stories/story-dispatch-window"]')).toBeVisible();
  expect(errors).toEqual([]);
});
